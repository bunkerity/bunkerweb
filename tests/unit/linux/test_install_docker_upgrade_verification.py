"""Docker upgrade verification of the easy-install script.

Port of dev ``0d3532e69`` (row 55 of fold-in 9). Four defects, all reachable on 1.7 before this:

* **.env was read first-wins, Compose reads it last-wins.** A file that declares a key twice --
  which is exactly what an operator produces by appending an override -- was carried over and
  re-loaded with the *first* value, so an upgrade silently re-rendered the stack against a value
  Compose never used. ``_docker_env_last_assignments`` now collapses the file the way Compose
  does, and refuses syntax it cannot round-trip instead of changing its effective value.
* **"every service reports running" was not evidence of an upgrade.** A scheduler crash-looping on
  a failed ``alembic upgrade head`` is *running* between restarts, and the old poll could sample it
  there. The wait now pins the image identity, the restart counter and the healthcheck, and
  requires the same set to stay healthy for ten seconds.
* **a hard-coded or digest-pinned image made the tag rewrite a no-op.** ``BW_TAG`` only reaches an
  image reference that interpolates it; a ``@sha256:`` pin or a hand-edited tag left the old
  version running while the installer reported an upgrade. Both are refused now, before anything
  is recreated.
* **the tag strip cut at the wrong colon.** ``localhost:5000/bunkerity/bunkerweb`` (a registry port,
  no tag) stripped to ``localhost``, so a stack on a private registry or a pull-through mirror fell
  out of the guard entirely. The strip now only fires when the *last path segment* carries a tag.

These run the extracted shell functions directly with stubbed ``docker`` / ``_docker_compose``: no
daemon, no host mutation, no ``sudo``.
"""

import os
import re
import subprocess
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[3] / "misc" / "install-bunkerweb.sh"


def _extract(*names):
    """Return the shell source of the named top-level functions, verbatim."""
    text = SCRIPT.read_text(encoding="utf-8")
    out = []
    for name in names:
        match = re.search(rf"^{re.escape(name)}\(\) \{{\n.*?^\}}\n", text, re.M | re.S)
        assert match, f"{name}() not found in {SCRIPT.name}"
        out.append(match.group(0))
    return "\n".join(out)


def _declarations():
    """The associative arrays live at top level, not in a function; without them `set -u` turns
    `_DOCKER_EXPECTED_IMAGES[bunkerweb]=` into an arithmetic subscript on an unbound variable."""
    text = SCRIPT.read_text(encoding="utf-8")
    match = re.search(r"^declare -A _DOCKER_EXPECTED_IMAGES.*$", text, re.M)
    assert match, "the verification arrays are no longer declared at top level"
    return match.group(0)


def _run(script):
    return subprocess.run(["bash", "-c", script], capture_output=True, text=True, env=os.environ | {"NO_COLOR": "1"})


# --------------------------------------------------------------------------- .env, last-wins


def test_the_env_view_is_the_one_compose_uses(tmp_path):
    """Compose keeps the last declaration of a key; so must every rewrite of the file."""
    env_file = tmp_path / ".env"
    env_file.write_text(
        "# generated by install-bunkerweb.sh\n"
        "\n"
        "HTTP_PORT=8080\n"
        "export  BW_TAG = 1.6.5\n"
        "HTTP_PORT=9090\n"
        "USE_BACKUP=no # operator note\n"
        "EMPTY=\n",
        encoding="utf-8",
    )
    out = _run(f'{_extract("_docker_env_last_assignments")}\n_docker_env_last_assignments "{env_file}"')

    assert out.returncode == 0, out.stderr
    assert out.stdout.splitlines() == ["BW_TAG=1.6.5", "HTTP_PORT=9090", "USE_BACKUP=no", "EMPTY="]


@pytest.mark.parametrize(
    "line",
    (
        'ADMIN_PASSWORD="quoted"',  # Compose strips the quotes; a verbatim rewrite would not
        "DATABASE_URI=mysql://u:p@h/${DB}",  # interpolation: the rewritten value would differ
        "TOKEN=back\\slash",  # Compose unescapes; we would not
        "NOTE=it's",  # same, for the single quote
        "this is not an assignment",  # multi-line value, YAML leftover, ...
    ),
)
def test_syntax_that_cannot_be_rewritten_is_refused(tmp_path, line):
    """Fail closed and name the line, rather than silently changing what the value means."""
    env_file = tmp_path / ".env"
    env_file.write_text(f"HTTP_PORT=8080\n{line}\n", encoding="utf-8")

    out = _run(f'{_extract("_docker_env_last_assignments")}\n_docker_env_last_assignments "{env_file}"')

    assert out.returncode == 1
    assert "Unsupported Docker .env syntax at line 2" in out.stderr
    assert out.stdout == "", "a refused file must not emit a half-parsed view"


def test_a_carried_over_key_keeps_its_effective_value(tmp_path):
    """The custom keys an upgrade re-appends must carry the value the stack was actually running."""
    old = tmp_path / "old.env"
    old.write_text("USE_BACKUP=yes\nUSE_BACKUP=no\n", encoding="utf-8")
    new = tmp_path / ".env"
    new.write_text("BW_TAG=1.7.0\n", encoding="utf-8")

    out = _run(f"""
        set -u
        print_status() {{ :; }}
        _bw_shred() {{ rm -f "$1"; }}
        DOCKER_ENV_FILE="{new}"
        _DOCKER_ENV_SNAPSHOT="{old}"
        {_extract("_docker_env_last_assignments", "_docker_restore_env_extras")}
        _docker_restore_env_extras
        """)

    assert out.returncode == 0, out.stderr
    assert new.read_text(encoding="utf-8").splitlines() == ["BW_TAG=1.7.0", "USE_BACKUP=no"]


