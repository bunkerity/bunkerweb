# ------------------------------------------------- every operator-supplied .env value is guarded


def _env_value_guard():
    """The `for _v in ...` loop of ask_docker_preferences, verbatim.

    Extracted rather than reproduced: the defect this covers was a variable *missing from the
    list*, so a test that restates the list would have been blind to it by construction.
    """
    text = SCRIPT.read_text(encoding="utf-8")
    match = re.search(r"^    local _v\n    for _v in .*?^    done\n", text, re.M | re.S)
    assert match, "the .env value guard loop is no longer where this test extracts it from"
    return match.group(0)


@pytest.mark.parametrize(
    "variable",
    (
        "UI_ADMIN_PASSWORD_INPUT",
        "DOCKER_DB_PASSWORD_GENERATED",
        "DOCKER_API_TOKEN_GENERATED",
        "DOCKER_DATABASE_URI",
        "API_USERNAME_INPUT",
        "API_PASSWORD_INPUT",
        "BUNKERWEB_INSTANCES_INPUT",
        "MANAGER_IP_INPUT",
        # 1.7 only: dev's .env has no API_URL key, so --api-url skipped the guard here and the
        # value reached the file. Since the upgrade re-read is now fail-closed, that turned a
        # mangled value into a stack this script can no longer upgrade at all.
        "DOCKER_API_URL",
    ),
)
def test_every_operator_supplied_env_value_is_refused_when_it_cannot_be_carried(variable):
    """`.env` is rewritten and re-read on every upgrade; a value it cannot round-trip is refused
    at the point the operator supplies it, not when the next upgrade tries to read it back."""
    empties = "\n".join(
        f'{name}=""'
        for name in (
            "UI_ADMIN_PASSWORD_INPUT",
            "DOCKER_DB_PASSWORD_GENERATED",
            "DOCKER_API_TOKEN_GENERATED",
            "DOCKER_DATABASE_URI",
            "API_USERNAME_INPUT",
            "API_PASSWORD_INPUT",
            "BUNKERWEB_INSTANCES_INPUT",
            "MANAGER_IP_INPUT",
            "DOCKER_API_URL",
        )
    )
    out = _run(f"""
        set -u
        print_error() {{ echo "ERROR: $*"; }}
        {empties}
        {variable}='http://user:p$w@api.internal:8888'
        {_extract("validate_docker_env_value")}
        guard() {{
        {_env_value_guard()}
        }}
        guard
        echo "NOT REFUSED"
        """)

    assert out.returncode == 1, out.stdout
    assert "NOT REFUSED" not in out.stdout
    assert "cannot carry safely" in out.stdout
