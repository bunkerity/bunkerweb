"""Behaviour of ``src/common/core/robotstxt/robotstxt.lua``, the real file run under plain Lua.

What an operator relies on: ``/robots.txt`` is answered by BunkerWeb only for services that enable the
plugin; the body is built from the per-service rule files (loaded in ``init``), the ``ROBOTSTXT_*``
settings (numbered variants in natural order, headers and footers base64-decoded) and the ignore
rules; with no rule the default "disallow everything" applies. OpenResty is stubbed at its boundary
(``_lua_plugin_helpers.py``); PCRE is replaced by Lua patterns.
"""

import base64

import pytest
from _lua_plugin_helpers import CORE, LUA, module_path, run_module, to_lua  # type: ignore

pytestmark = pytest.mark.skipif(LUA is None, reason="no lua interpreter on PATH")

MODULE = module_path("ROBOTSTXT", CORE / "robotstxt" / "robotstxt.lua")
SERVER = "www.example.com"
DEFAULT_RULES = ["User-agent: *", "Disallow: /"]
BANNER = "# robots.txt generated by BunkerWeb (https://bunkerweb.io)"


def b64(text):
    return base64.b64encode(text.encode()).decode()


def serve(env=None, *, stored=None, multisite="yes", uri="/robots.txt", enabled="yes", server_name=SERVER, setup=""):
    """Build the plugin through the real ``initialize`` (rules from the store + settings) and run ``access``."""
    body = f"""
VARIABLES = {to_lua({"USE_ROBOTSTXT": enabled})}
GETVAR = {to_lua({"MULTISITE": multisite})}
MULTI_VARS = {to_lua({server_name if multisite == "yes" else "global": env or {}})}
STORE["plugin_robotstxt_rules_{server_name}"] = {to_lua(stored) if stored is not None else "nil"}
{setup}
local plugin = new_plugin(PLUGIN, {to_lua({"uri": uri, "server_name": server_name})})
local result = plugin:access()
emit({{
    ret = result.ret, msg = result.msg, ok = result.status == ngx.OK, said = SAID,
    content_type = ngx.header["Content-Type"], logs = LOGS,
}})
"""
    return run_module(MODULE, body)


def lines(out):
    assert len(out["said"]) == 1
    return out["said"][0].split("\n")


class TestWhenItAnswers:
    def test_a_disabled_service_does_not_answer_robots_txt(self):
        out = serve({"ROBOTSTXT_RULE": "Disallow: /x"}, enabled="no")
        assert (out["ret"], out["msg"], out["ok"]) == (True, "success", False)
        assert not out["said"]

    def test_other_uris_are_left_alone(self):
        out = serve({"ROBOTSTXT_RULE": "Disallow: /x"}, uri="/index.html")
        assert out["msg"] == "success"
        assert not out["said"]

    def test_the_answer_is_plain_text_and_ends_the_request(self):
        out = serve({"ROBOTSTXT_RULE": "Disallow: /x"})
        assert (out["msg"], out["ok"]) == ("served robots.txt", True)
        assert out["content_type"] == "text/plain; charset=utf-8"

    def test_the_default_server_is_never_a_robots_txt_service_from_a_request_phase(self):
        # server "_" skips the per-request shortcut and asks whether *any* service enables the plugin
        out = serve({"ROBOTSTXT_RULE": "Disallow: /x"}, server_name="_", enabled="no", setup="HAS_VARIABLE = false")
        assert out["msg"] == "success"
        assert not out["said"]


class TestBodyAssembly:
    def test_with_no_rule_the_default_disallow_all_applies(self):
        out = serve({})
        assert lines(out) == [BANNER, *DEFAULT_RULES]

    def test_rules_come_from_the_settings(self):
        out = serve({"ROBOTSTXT_RULE": "User-agent: Bot", "ROBOTSTXT_RULE_1": "Disallow: /private"})
        assert lines(out) == [BANNER, "User-agent: Bot", "Disallow: /private"]

    def test_numbered_variables_are_in_natural_order_not_text_order(self):
        env = {f"ROBOTSTXT_RULE_{n}": f"rule-{n}" for n in (10, 2, 1)} | {"ROBOTSTXT_RULE": "rule-0"}
        out = serve(env)
        assert lines(out)[1:] == ["rule-0", "rule-1", "rule-2", "rule-10"]

    def test_the_sections_come_in_a_fixed_order_with_sitemap_prefixed(self):
        env = {
            "ROBOTSTXT_FOOTER": b64("# footer"),
            "ROBOTSTXT_SITEMAP": "https://www.example.com/sitemap.xml",
            "ROBOTSTXT_RULE": "Disallow: /x",
            "ROBOTSTXT_HEADER": b64("# header"),
        }
        assert lines(serve(env)) == [BANNER, "# header", "Disallow: /x", "Sitemap: https://www.example.com/sitemap.xml", "# footer"]

    def test_a_header_that_is_not_base64_is_used_as_is(self):
        out = serve({"ROBOTSTXT_HEADER": "!!not base64!!", "ROBOTSTXT_RULE": "Disallow: /x"})
        assert lines(out)[1] == "!!not base64!!"

    def test_empty_values_are_skipped(self):
        out = serve({"ROBOTSTXT_RULE": "", "ROBOTSTXT_RULE_1": "Disallow: /x", "ROBOTSTXT_SITEMAP": ""})
        assert lines(out) == [BANNER, "Disallow: /x"]

    def test_rules_stored_by_init_come_before_the_setting_rules(self):
        out = serve({"ROBOTSTXT_RULE": "from-setting"}, stored=["from-file-1", "from-file-2"])
        assert lines(out)[1:] == ["from-file-1", "from-file-2", "from-setting"]

    def test_the_shared_store_entry_is_not_modified_by_a_request(self):
        body = f"""
VARIABLES = {to_lua({"USE_ROBOTSTXT": "yes"})}
GETVAR = {to_lua({"MULTISITE": "yes"})}
MULTI_VARS = {to_lua({SERVER: {"ROBOTSTXT_RULE": "from-setting"}})}
STORE["plugin_robotstxt_rules_{SERVER}"] = {{ "from-file" }}
new_plugin(PLUGIN, {{ uri = "/robots.txt" }})
new_plugin(PLUGIN, {{ uri = "/robots.txt" }})
emit(STORE["plugin_robotstxt_rules_{SERVER}"])
"""
        assert run_module(MODULE, body) == ["from-file"]

    def test_a_missing_store_entry_is_logged_and_the_settings_still_apply(self):
        out = serve({"ROBOTSTXT_RULE": "Disallow: /x"}, stored=None)
        assert lines(out) == [BANNER, "Disallow: /x"]
        assert any(level == "ERR" and "no such key plugin_robotstxt_rules_" in msg for level, msg in out["logs"])

    def test_singlesite_reads_the_global_variables(self):
        out = serve({"ROBOTSTXT_RULE": "Disallow: /global"}, multisite="no")
        assert lines(out)[1:] == ["Disallow: /global"]

    def test_the_loaded_counts_are_logged(self):
        out = serve({"ROBOTSTXT_RULE": "Disallow: /x", "ROBOTSTXT_SITEMAP": "https://e/s.xml"})
        assert ["INFO", f"loaded 1 rules and 1 sitemaps for the service: {SERVER}"] in out["logs"]


class TestIgnoreRules:
    def test_a_rule_matching_an_ignore_rule_is_dropped(self):
        env = {"ROBOTSTXT_RULE": "Disallow: /keep", "ROBOTSTXT_RULE_1": "Disallow: /private", "ROBOTSTXT_IGNORE_RULE": "private"}
        assert lines(serve(env))[1:] == ["Disallow: /keep"]

    def test_stored_rules_are_filtered_too(self):
        out = serve({"ROBOTSTXT_IGNORE_RULE_1": "GPTBot"}, stored=["User-agent: GPTBot", "User-agent: Other"])
        assert lines(out)[1:] == ["User-agent: Other"]

    def test_ignoring_every_rule_falls_back_to_the_default(self):
        out = serve({"ROBOTSTXT_RULE": "Disallow: /x", "ROBOTSTXT_IGNORE_RULE": "Disallow"})
        assert lines(out)[1:] == DEFAULT_RULES

    def test_ignore_rules_never_filter_sitemaps(self):
        env = {"ROBOTSTXT_SITEMAP": "https://e/private.xml", "ROBOTSTXT_RULE": "Disallow: /x", "ROBOTSTXT_IGNORE_RULE": "private"}
        assert "Sitemap: https://e/private.xml" in lines(serve(env))


class TestInit:
    @staticmethod
    def init(files, *, enabled=True, server_name=SERVER, setup="", tmp_path=None):
        for rel, content in files.items():
            path = tmp_path / "robotstxt" / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        body = f"""
PHASE = "init"
IS_REQUEST = false
HAS_VARIABLE = {"true" if enabled else "false"}
GETVAR = {to_lua({"SERVER_NAME": server_name})}
{setup}
local result = new_plugin(PLUGIN, {{}}):init()
emit({{ ret = result.ret, msg = result.msg, store = STORE, logs = LOGS }})
"""
        return run_module(MODULE, body, fs_root=tmp_path)

    def test_init_is_skipped_when_no_service_uses_the_plugin(self, tmp_path):
        out = self.init({}, enabled=False, tmp_path=tmp_path)
        assert (out["ret"], out["msg"], out["store"]) == (True, "init not needed", {})

    def test_rules_files_are_loaded_per_service_without_the_darkvisitors_header_line(self, tmp_path):
        files = {
            f"{SERVER}/darkvisitors.list": "# generated header\nUser-agent: GPTBot\nDisallow: /\n",
            f"{SERVER}/rules.list": "User-agent: Mine\n\nDisallow: /mine\n",
            "other.example.com/rules.list": "User-agent: Other\n",
        }
        out = self.init(files, server_name=f"{SERVER} other.example.com", tmp_path=tmp_path)
        assert (out["ret"], out["msg"]) == (True, "successfully loaded all robots.txt rules from files")
        assert out["store"][f"plugin_robotstxt_rules_{SERVER}"] == ["User-agent: GPTBot", "Disallow: /", "User-agent: Mine", "Disallow: /mine"]
        assert out["store"]["plugin_robotstxt_rules_other.example.com"] == ["User-agent: Other"]

    def test_a_service_without_files_gets_an_empty_rule_list(self, tmp_path):
        out = self.init({}, tmp_path=tmp_path)
        assert out["store"] == {f"plugin_robotstxt_rules_{SERVER}": {}}

    def test_a_store_failure_aborts_init_with_the_service_named(self, tmp_path):
        out = self.init({}, tmp_path=tmp_path, setup='STORE_SET_ERROR = "shared dict full"')
        assert out["ret"] is False
        assert out["msg"] == f"can't store robotstxt rules for {SERVER} into internalstore : shared dict full"

    def test_an_unreadable_server_name_aborts_init(self, tmp_path):
        out = self.init({}, tmp_path=tmp_path, setup="GETVAR = {}")
        assert out["ret"] is False
        assert out["msg"] == "can't get SERVER_NAME variable : no such variable SERVER_NAME"


class TestSettingsReadFailures:
    def test_a_failed_settings_read_is_logged(self):
        out = serve({"ROBOTSTXT_RULE": "Disallow: /x"}, stored=["from-file"], setup='MULTI_ERR = "redis down"')
        assert any(level == "ERR" and "redis down" in msg for level, msg in out["logs"])

    def test_a_failed_settings_read_still_serves_the_rules_stored_by_init(self):
        out = serve({"ROBOTSTXT_RULE": "Disallow: /x"}, stored=["from-file"], setup='MULTI_ERR = "redis down"')
        assert lines(out)[1:] == ["from-file"]
