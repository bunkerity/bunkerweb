struct NamedEntity {
    const char *name;
    std::size_t len;
    unsigned char ch;
};

/* Named-entity table for t:htmlEntityDecode.
 *
 * Compared case-insensitively against the full extracted token; the length
 * must match exactly.  Prior implementations used strncasecmp() with the name
 * length only, which caused prefix collisions (e.g. "&ltest;" decoded to "<"
 * and dropped "est").  See GHSA-cxqf-vgrr-xxrv.
 *
 * The contents below are generated, not hand-curated: a hand-written list
 * drifts from the specification (it is how &lcub;, &excl; and &Hat; came to
 * be missing while &caret;, &hyphen; and &tilde; were mapped to ASCII
 * characters the specification does not assign them).  Regenerate with:
 *
 *     curl -sSO https://html.spec.whatwg.org/entities.json
 *     python3 tools/gen-html-entities.py entities.json
 *
 * NAMED_ENTITY derives the name length from the string literal at compile
 * time so the two cannot drift out of sync.
 */
#define NAMED_ENTITY(name_lit, character) \
    { (name_lit), sizeof(name_lit) - 1, static_cast<unsigned char>(character) }

constexpr NamedEntity named_entities[] = {
    /* Generated by tools/gen-html-entities.py from
     * https://html.spec.whatwg.org/entities.json -- do not edit by hand.
     *
     * Every entity expanding to a single code point in U+0000..U+007F,
     * plus NBSP (U+00A0) and SOFT HYPHEN (U+00AD).  44 entries.
     *
     * Case-insensitive matching collapses these spec distinctions:
     *   &GT; = U+003E wins over &Gt; = U+226B
     *   &LT; = U+003C wins over &Lt; = U+226A
     *   &colon; = U+003A wins over &Colon; = U+2237
     *   &verbar; = U+007C wins over &Verbar; = U+2016
     *   &vert; = U+007C wins over &Vert; = U+2016
     */
    NAMED_ENTITY("amp",              '&'),
    NAMED_ENTITY("apos",             '\''),
    NAMED_ENTITY("ast",              '*'),
    NAMED_ENTITY("bsol",             '\\'),
    NAMED_ENTITY("colon",            ':'),
    NAMED_ENTITY("comma",            ','),
    NAMED_ENTITY("commat",           '@'),
    NAMED_ENTITY("diacriticalgrave", '`'),
    NAMED_ENTITY("dollar",           '$'),
    NAMED_ENTITY("equals",           '='),
    NAMED_ENTITY("excl",             '!'),
    NAMED_ENTITY("grave",            '`'),
    NAMED_ENTITY("gt",               '>'),
    NAMED_ENTITY("hat",              '^'),
    NAMED_ENTITY("lbrace",           '{'),
    NAMED_ENTITY("lbrack",           '['),
    NAMED_ENTITY("lcub",             '{'),
    NAMED_ENTITY("lowbar",           '_'),
    NAMED_ENTITY("lpar",             '('),
    NAMED_ENTITY("lsqb",             '['),
    NAMED_ENTITY("lt",               '<'),
    NAMED_ENTITY("midast",           '*'),
    NAMED_ENTITY("nbsp",             NBSP),
    NAMED_ENTITY("newline",          '\n'),
    NAMED_ENTITY("nonbreakingspace", NBSP),
    NAMED_ENTITY("num",              '#'),
    NAMED_ENTITY("percnt",           '%'),
    NAMED_ENTITY("period",           '.'),
    NAMED_ENTITY("plus",             '+'),
    NAMED_ENTITY("quest",            '?'),
    NAMED_ENTITY("quot",             '\"'),
    NAMED_ENTITY("rbrace",           '}'),
    NAMED_ENTITY("rbrack",           ']'),
    NAMED_ENTITY("rcub",             '}'),
    NAMED_ENTITY("rpar",             ')'),
    NAMED_ENTITY("rsqb",             ']'),
    NAMED_ENTITY("semi",             ';'),
    NAMED_ENTITY("shy",              0xAD),
    NAMED_ENTITY("sol",              '/'),
    NAMED_ENTITY("tab",              '\t'),
    NAMED_ENTITY("underbar",         '_'),
    NAMED_ENTITY("verbar",           '|'),
    NAMED_ENTITY("vert",             '|'),
    NAMED_ENTITY("verticalline",     '|'),
};

#undef NAMED_ENTITY

bool lookup_named_entity(const unsigned char *name, std::size_t name_len,
                         unsigned char *out) {
    for (const auto &e : named_entities) {
        if (e.len == name_len &&
            strncasecmp(reinterpret_cast<const char *>(name), e.name,
                        name_len) == 0) {
            *out = e.ch;
            return true;
        }
    }
    return false;
}

